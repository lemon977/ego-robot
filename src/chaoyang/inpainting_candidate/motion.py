"""Thin offline visual Motion consumer over sealed Source and frozen V1 core.

This is not an entry point: the registered CPU geometry worker owns its fence.
Importing this module does not construct Robot, run IK/FK or load model weights.
Raw parsing and adopted-camera binding remain the existing motion_source bridge.
No historical actions, source.npz, seeds, Mask/Clean or placement are accepted.
"""
from __future__ import annotations

from copy import deepcopy
import json
from pathlib import Path
import re
from typing import Any, Mapping

import numpy as np

from . import motion_source
from .contracts import SCHEMA, canonical_sha, file_ref, verify_ref, verify_sealed_stage

PROJECT_ROOT = Path(__file__).resolve().parents[3]
TIMEBASE = "TIMEBASE_UNVERIFIED_HOST_ARRIVAL_QPC_DECLARED_NS"
BASE_RULE = "gravity_upright_heading_mean_camera_shoulder_prior_grid_v1"
PARENT_GATES = {"track_position_mm": 20.0, "track_rotation_deg": 15.0,
                "arm_speed_rad_s": 3.6, "arm_accel_rad_s2": 54.0}
CODE_CLOSURE = ("src/chaoyang/exact78_baseline/retarget.py",
                "src/chaoyang/exact78_baseline/robot_model.py",
                "src/chaoyang/inpainting_candidate/motion_source.py",
                "src/chaoyang/pipeline/robot_renderer_cycles.py",
                "src/chaoyang/pipeline/robot_renderer_eevee_fullchain.py",
                "src/chaoyang/pipeline/robot_wrist_kai_adapter.py",
                "src/chaoyang/pipeline/robot_tool_definition_contract.py",
                "src/chaoyang/pipeline/robot_mount_visual_proxy.py",
                "src/chaoyang/ops/immutable_artifact_io.py")


class MotionStageError(ValueError):
    pass


def _load_robot(repo_root: Path):
    from chaoyang.exact78_baseline.robot_model import Robot
    return Robot(repo_root)


def _retarget_session(session, robot):
    from chaoyang.exact78_baseline.retarget import retarget_session
    return retarget_session(session, robot)


def _read(reference: Mapping) -> Any:
    verify_ref(reference)
    return json.loads(Path(reference["path"]).read_text(encoding="utf-8-sig"))


def _signature(value, kind: str) -> str:
    if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value):
        raise MotionStageError(f"MOTION_{kind}_SIGNATURE_REQUIRED")
    return value


def _source(source_ref: Mapping, signature: str) -> tuple[dict, dict, list[dict], dict]:
    receipt = _read(source_ref)
    if receipt.get("stage") != "Source":
        raise MotionStageError("MOTION_SEALED_SOURCE_REQUIRED")
    root = Path(source_ref["path"]).resolve(strict=True).parent
    outputs = verify_sealed_stage(receipt, signature, output_root=root)
    names = {Path(item["path"]).name: item for item in outputs}
    if not {"RAW_RGB.npz", "FRAME_MAP.json", "SOURCE_REPORT.json"} <= names.keys():
        raise MotionStageError("MOTION_SOURCE_OUTPUT_CONTRACT_INCOMPLETE")
    report = _read(names["SOURCE_REPORT.json"])
    mapping = _read(names["FRAME_MAP.json"])
    count = receipt.get("native_frames")
    if (type(count) is not int or count < 1 or not isinstance(mapping, list)
            or len(mapping) != count or report.get("native_sidecar_frames") != count
            or receipt.get("session_id") != report.get("session_id")):
        raise MotionStageError("MOTION_SOURCE_NATIVE_IDENTITY_MISMATCH")
    declared = report.get("frame_mapping", [])
    if len(declared) != count:
        raise MotionStageError("MOTION_SOURCE_FRAME_MAP_INCOMPLETE")
    for index, row in enumerate(mapping):
        if (not isinstance(row, dict)
                or any(type(row.get(key)) is not int or row[key] != index for key in
                       ("native_frame_index", "decoded_display_index", "model_input_frame", "output_frame"))
                or type(row.get("qpc_declared_ns")) is not int
                or row["qpc_declared_ns"] != declared[index].get("qpc_declared_ns")
                or row.get("sbs_index") != report.get("camera", {}).get("sbs_index")
                or row.get("physical_eye") != report.get("camera", {}).get("physical_eye")):
            raise MotionStageError("MOTION_SOURCE_FRAME_MAPPING_CHANGED")
    qpc = np.asarray([row["qpc_declared_ns"] for row in mapping], dtype=np.int64)
    if np.any(np.diff(qpc) <= 0):
        raise MotionStageError("MOTION_QPC_DUPLICATE_OR_BACKWARD")
    # The decoded map is authoritative. Do not replace UNKNOWN acquisition IDs
    # or missing decoder PTS with the index generated by a motion parser.
    report = deepcopy(report)
    report["frame_mapping"] = deepcopy(mapping)
    return receipt, report, mapping, names


def _camera_contract(contract: Mapping, report: Mapping, repo: Path) -> dict:
    if not isinstance(contract, Mapping) or set(contract) != {"v1_manifest", "camera_config"}:
        raise MotionStageError("MOTION_FROZEN_CAMERA_CONTRACT_REQUIRED")
    manifest_ref, config_ref = contract["v1_manifest"], contract["camera_config"]
    if Path(manifest_ref["path"]).resolve(strict=True) != repo / "inpainting_v1/MANIFEST.json":
        raise MotionStageError("MOTION_ONLY_CURRENT_V1_CAMERA_CONTRACT_ALLOWED")
    manifest = _read(manifest_ref)
    if (manifest.get("baseline_id") != "INPAINTING_RAW_TO_ROBOT_V1"
            or manifest.get("inputs", {}).get("camera") != config_ref):
        raise MotionStageError("MOTION_ADOPTED_CAMERA_CONTRACT_MISMATCH")
    verify_ref(config_ref)
    adopted = report.get("adopted_route_contracts", [])
    if adopted and any(ref not in adopted for ref in (manifest_ref, config_ref)):
        raise MotionStageError("MOTION_CAMERA_NOT_BOUND_BY_SOURCE")
    return dict(manifest_ref)


def _unique_refs(rows) -> list[dict]:
    result = {}
    for row in rows:
        row = dict(row)
        if row["path"] in result and result[row["path"]] != row:
            raise MotionStageError("MOTION_ACTUAL_INPUT_REFERENCE_CONFLICT")
        result[row["path"]] = row
    return [result[path] for path in sorted(result)]


def _robot_asset_refs(repo: Path, robot) -> list[dict]:
    """Bind exactly what Robot loaded, not an assets-directory glob.

    The frozen loader verifies all 63 visual meshes even when IK subsequently
    uses only fingertip geometry. The flange STL belongs to Render, not Motion.
    """
    pin_ref = dict(robot.assets.asset_pin_record)
    if Path(pin_ref["path"]).resolve(strict=True) != repo / "assets/robot/ROBOT_ASSET_PIN.json":
        raise MotionStageError("MOTION_ROBOT_ASSET_PIN_PATH_DRIFT")
    pin = _read(pin_ref)
    if pin.get("status") != "T0_IDENTITY_PIN_NOT_EXECUTION_AUTHORIZATION":
        raise MotionStageError("MOTION_ROBOT_ASSET_PIN_STATUS_DRIFT")
    entries = {row["path"]: row for row in pin.get("files", [])}
    urdfs = [row["path"] for row in pin.get("urdfs", [])]
    meshes = list(robot.assets.mesh_records)
    if len(urdfs) != 3 or len(set(urdfs)) != 3 or len(meshes) != 63:
        raise MotionStageError("MOTION_ROBOT_ASSET_CLOSURE_INCOMPLETE")
    result = [pin_ref]
    for relative in [*urdfs, *meshes]:
        path = (repo / relative).resolve(strict=True)
        if not path.is_relative_to(repo / "assets/robot") or relative not in entries:
            raise MotionStageError("MOTION_ROBOT_ASSET_NOT_PINNED")
        expected = entries[relative]
        reference = {"path": str(path), "bytes": expected["bytes"], "sha256": expected["sha256"]}
        verify_ref(reference)
        result.append(reference)
    result.append(file_ref(repo / "assets/robot/hardware_handoff/kaihand_flange_adapter_v1/"
                           "excluded_reference_only/MOUNT_VISUAL_PROXY_CONTRACT.json"))
    return _unique_refs(result)


def _motion_arrays(session, robot, result) -> tuple[dict, np.ndarray, np.ndarray]:
    count = session.frame_count
    shapes = {"q_arm": (count, 2, 7), "q_hand": (count, 2, 22),
              "T_world_base": (4, 4), "root_world": (2, count, 4, 4),
              "arm_position_mm": (2, count), "arm_rotation_deg": (2, count),
              "hand_bone_deg": (2, count)}
    arrays = {}
    for key, shape in shapes.items():
        value = np.asarray(getattr(result, key))
        if (value.shape != shape or value.dtype.hasobject or not np.isfinite(value).all()):
            raise MotionStageError(f"MOTION_RESULT_ARRAY_INVALID:{key}")
        arrays[key] = value
    if result.metrics.get("gates") != PARENT_GATES:
        raise MotionStageError("MOTION_FROZEN_PARENT_NUMERIC_GATES_DRIFT")
    if result.base_report.get("rule") != BASE_RULE:
        raise MotionStageError("MOTION_AUTOMATIC_BASE_RULE_DRIFT")
    qpc = np.asarray(session.qpc_ns)
    if qpc.dtype.kind not in "iu" or qpc.shape != (count,) or np.any(np.diff(qpc) <= 0):
        raise MotionStageError("MOTION_NATIVE_QPC_INVALID")
    dt = np.diff(qpc).astype(np.float64) / 1e9
    velocity = np.diff(arrays["q_arm"], axis=0) / dt[:, None, None]
    acceleration = np.diff(velocity, axis=0) / ((dt[:-1] + dt[1:]) / 2)[:, None, None]
    speed_bad, accel_bad = np.zeros((count, 2), bool), np.zeros((count, 2), bool)
    speed_bad[1:] = (abs(velocity) > PARENT_GATES["arm_speed_rad_s"]).any(axis=2)
    accel_bad[2:] = (abs(acceleration) > PARENT_GATES["arm_accel_rad_s2"]).any(axis=2)
    tracking = ((arrays["arm_position_mm"] <= PARENT_GATES["track_position_mm"])
                & (arrays["arm_rotation_deg"] <= PARENT_GATES["track_rotation_deg"]))
    arrays.update(K=np.asarray(session.K), c2w=np.asarray(session.c2w),
                  c2w_factory=np.asarray(session.c2w_editor), qpc_ns=qpc,
                  hand_source=np.asarray(session.hand_source),
                  hand_observed=np.asarray(session.hand_observed),
                  arm_tracking_valid=tracking.T,
                  arm_velocity_rad_s=velocity, arm_acceleration_rad_s2=acceleration,
                  qpc_velocity_violation=speed_bad, qpc_acceleration_violation=accel_bad,
                  q_arm_joint_names=np.asarray([tuple(chain.joint_names) for chain in robot.arms], dtype="U64"),
                  q_hand_joint_names=np.asarray([tuple(hand.names) for hand in robot.hands], dtype="U64"))
    arrays.update({key: np.asarray(value) for key, value in session.motion_valid.items()})
    return arrays, speed_bad, accel_bad


def _frame_status(session, arrays: Mapping, mapping: list[dict], raw_inputs: Mapping) -> list[dict]:
    rows = []
    input_shas = {key: pin["sha256"] for key, pin in raw_inputs.items()}
    for index, source in enumerate(mapping):
        sides = {}
        for side, name in enumerate(("left", "right")):
            tracking = bool(arrays["arm_tracking_valid"][index, side])
            speed = bool(arrays["qpc_velocity_violation"][index, side])
            accel = bool(arrays["qpc_acceleration_violation"][index, side])
            observed = bool(session.hand_observed[side, index])
            head_valid = bool(session.motion_valid["head_valid"][index])
            sides[name] = {"roi_source": "NOT_CONSUMED", "visibility": "UNKNOWN",
                "motion_source": str(session.hand_source[side, index]),
                "motion_authority": "RAW_CONTROLLER_MANUS_INSTALLATION_PRIOR_NOT_CONTROL_TRUTH",
                "wrist_position_valid": bool(session.motion_valid["controller_valid"][index, side]),
                "wrist_orientation_valid": bool(session.motion_valid["controller_valid"][index, side]),
                "local_handshape_valid": bool(session.motion_valid["manus_valid"][index, side]),
                "source_evidence_valid": observed and head_valid,
                "display_valid": bool(session.motion_valid["hand_display_valid"][side, index]),
                "robot_status": "TRACK_GATE_FAIL" if not tracking else
                                "MOTION_LIMIT_FAIL" if speed or accel else
                                "SOURCE_EVIDENCE_INVALID" if not observed or not head_valid else "CANDIDATE",
                "arm_position_mm": float(arrays["arm_position_mm"][side, index]),
                "arm_rotation_deg": float(arrays["arm_rotation_deg"][side, index]),
                "hand_bone_deg": float(arrays["hand_bone_deg"][side, index]),
                "tracking_valid": tracking, "velocity_limit_fail": speed,
                "acceleration_limit_fail": accel, "training_eligible": False}
        native_route = {}
        for key, values in session.mapping.items():
            value = np.asarray(values)[index]
            native_route[key] = value.tolist() if isinstance(value, np.ndarray) else value.item() if isinstance(value, np.generic) else value
        rows.append({"native_frame_index": index, "source_frame_map": deepcopy(source),
            "acquisition_frame_id": source.get("acquisition_frame_id", "UNKNOWN"),
            "qpc_declared_ns": source["qpc_declared_ns"], "timebase_status": TIMEBASE,
            "time_mode": "OFFLINE_NONCAUSAL_RETARGET_AND_DISPLAY_FILL",
            "native_motion_mapping": native_route, "raw_input_sha256": input_shas,
            "hands": sides, "projection_qualified": False, "control_ground_truth": False,
            "training_eligible": False})
    return rows


def build_motion_stage(*, source_receipt: Mapping, source_signature: str,
                       output_dir: str | Path, component_signature: str,
                       raw_inputs: Mapping, camera_contract: Mapping,
                       repo_root: str | Path) -> dict:
    """Seal Motion; numeric FAIL remains per-frame, not a whole-session exit.

    Called only by the registered fenced CPU worker. Unsupported native/camera
    evidence is locally sealed as blocked Robot consumption, not fabricated q.
    """
    _signature(source_signature, "SOURCE")
    _signature(component_signature, "COMPONENT")
    repo = Path(repo_root).resolve(strict=True)
    root = Path(output_dir).resolve()
    if repo != PROJECT_ROOT.resolve() or root == repo or not root.is_relative_to(repo):
        raise MotionStageError("MOTION_OUTPUT_OR_REPO_OUTSIDE_PROJECT")
    if root.exists():
        raise MotionStageError("MOTION_FRESH_OUTPUT_REQUIRED")
    upstream, report, mapping, source_outputs = _source(source_receipt, source_signature)
    if not isinstance(raw_inputs, Mapping) or dict(raw_inputs) != report.get("actual_inputs"):
        raise MotionStageError("MOTION_RAW_INPUT_BINDING_MISMATCH")
    camera_manifest = _camera_contract(camera_contract, report, repo)
    root.mkdir(parents=True, exist_ok=False)
    native_signature = canonical_sha({"stage": "MotionSource", "Motion": component_signature,
                                      "Source": source_signature})
    native = motion_source.prepare_motion_source(report, root / "Native",
        component_signature=native_signature,
        v1_manifest_ref=camera_manifest)
    if native["receipt"].get("stage") != "MotionSource":
        raise MotionStageError("MOTION_NATIVE_SOURCE_STAGE_CHANGED")
    verify_sealed_stage(native["receipt"], native_signature, output_root=root / "Native")
    session = native["raw_session"]
    native_ref = file_ref(root / "Native/RECEIPT.json")
    refs = _unique_refs([dict(source_receipt), source_outputs["FRAME_MAP.json"],
        source_outputs["SOURCE_REPORT.json"], native_ref, *native["receipt"]["actual_inputs"],
        *native["receipt"]["outputs"], file_ref(Path(__file__)),
        *[file_ref(repo / path) for path in CODE_CLOSURE]])
    robot, result, arrays, states = None, None, {}, []
    blocked = None
    if session is None:
        blocked = native["report"]["camera_binding"].get("failure_code", "CAMERA_NOT_READY")
    elif (session.frame_count != len(mapping)
            or not np.array_equal(session.qpc_ns, [row["qpc_declared_ns"] for row in mapping])):
        raise MotionStageError("MOTION_PARSED_NATIVE_IDENTITY_CHANGED")
    elif any(not np.isfinite(np.asarray(value)).all() for value in (session.hands, session.c2w, session.K)):
        blocked = "NONFINITE_NATIVE_MOTION_NOT_SOLVABLE"
    else:
        robot = _load_robot(repo)
        refs = _unique_refs([*refs, *_robot_asset_refs(repo, robot)])
        result = _retarget_session(session, robot)
        arrays, _, _ = _motion_arrays(session, robot, result)
        states = _frame_status(session, arrays, mapping, raw_inputs)
    if blocked is not None:
        arrays = {"qpc_ns": np.asarray([row["qpc_declared_ns"] for row in mapping], np.int64)}
        states = [{"native_frame_index": index, "source_frame_map": deepcopy(row),
            "acquisition_frame_id": row.get("acquisition_frame_id", "UNKNOWN"),
            "qpc_declared_ns": row["qpc_declared_ns"], "timebase_status": TIMEBASE,
            "robot_status": "BLOCKED", "failure_code": blocked,
            "control_ground_truth": False, "training_eligible": False} for index, row in enumerate(mapping)]
    motion_report = {"schema": "inpainting-candidate-motion-v1",
        "session_id": upstream["session_id"], "native_frames": len(mapping),
        "status": "COMPLETE_MOTION_ACTIONS" if result is not None else "COMPLETE_NATIVE_LOCAL_ROBOT_BLOCKED",
        "actual_motion_source": "RAW_CONTROLLER_HEAD_PLUS_RAW_MANUS",
        "kinematic_actions_generated": result is not None,
        "robot_consumer_status": "READY_OFFLINE_VISUAL_CANDIDATE" if result is not None else "BLOCKED",
        "failure_code": blocked, "parent_solver": "chaoyang.exact78_baseline.retarget.retarget_session",
        "base": deepcopy(result.base_report) if result is not None else None,
        "metrics": deepcopy(result.metrics) if result is not None else None,
        "native_motion_source": native_ref, "camera_binding": native["report"]["camera_binding"],
        "calibration": deepcopy(session.calibration) if session is not None else None,
        "actual_inputs": refs, "native_image_size": [session.width, session.height] if session is not None else None,
        "units": {"q_arm": "radian", "q_hand": "radian", "translation": "metre",
                  "side_order": ["left", "right"], "T_world_base": "p_world=T_world_base@p_base",
                  "c2w": "p_world=c2w@p_camera"},
        "timebase_status": TIMEBASE, "qpc_unit": "DECLARED_NS_NOT_INDEPENDENTLY_VERIFIED",
        "qpc_frequency": "ABSENT", "qpc_sampling_position": "UNKNOWN",
        "time_mode": "OFFLINE_NONCAUSAL_RETARGET_AND_DISPLAY_FILL",
        "qpc_violations": {"velocity_per_side": arrays["qpc_velocity_violation"].sum(axis=0).tolist(),
            "acceleration_per_side": arrays["qpc_acceleration_violation"].sum(axis=0).tolist()} if result is not None else None,
        "visual_quality": "NOT_REVIEWED", "human_review": "PENDING",
        "projection_qualified": False, "control_ground_truth": False, "training_eligible": False,
        "historical_actions_read": False, "historical_placement_read": False,
        "hdf5_datasets_read": False, "model_calls": 0,
        "robot_asset_loads": int(robot is not None), "retarget_calls": int(result is not None)}
    for reference in refs:
        verify_ref(reference)
    outputs = [motion_source._npz(root / "MOTION.npz", arrays),
        motion_source._json(root / "FRAME_MAP.json", mapping),
        motion_source._json(root / "FRAME_STATUS.json", states),
        motion_source._json(root / "MOTION_REPORT.json", motion_report),
        native_ref, *native["receipt"]["outputs"]]
    receipt = {"schema": SCHEMA, "stage": "Motion", "status": "SEALED_COMPLETE",
        "component_signature": component_signature, "source_signature": source_signature,
        "source_receipt": dict(source_receipt), "session_id": upstream["session_id"],
        "native_frames": len(mapping), "outputs": outputs, "actual_inputs": refs,
        "consumer_status": {"Render": motion_report["robot_consumer_status"],
                            "Mask": "INDEPENDENT", "Clean": "INDEPENDENT"},
        "kinematic_actions_generated": result is not None, "failure_code": blocked,
        "timebase_status": TIMEBASE, "projection_qualified": False,
        "control_ground_truth": False, "training_eligible": False,
        "visual_quality": "NOT_REVIEWED", "human_review": "PENDING", "model_calls": 0,
        "robot_asset_loads": int(robot is not None), "retarget_calls": int(result is not None)}
    motion_source._json(root / "RECEIPT.json", receipt)
    return receipt
